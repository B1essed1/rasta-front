function useBigText(){
  const [on, setOn] = React.useState(()=>{ try{ return localStorage.getItem("rasta.bigtext")==="1"; }catch(e){ return false; } });
  React.useEffect(()=>{ document.documentElement.classList.toggle("ez-big", on); try{ localStorage.setItem("rasta.bigtext", on?"1":"0"); }catch(e){} }, [on]);
  return [on, setOn];
}

